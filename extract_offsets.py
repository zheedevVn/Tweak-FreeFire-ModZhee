import os
import sys
import re

TARGET_METHODS = {
    # Bones
    "GetHeadPositions": [r"Transform GetHeadTF\(\)"],
    "newHipMods": [r"Transform GetHipTF\(\)"],
    "GetLeftAnkleTF": [r"Transform GetLeftAnkleTF\(\)"],
    "GetRightAnkleTF": [r"Transform GetRightAnkleTF\(\)"],
    "GetLeftToeTF": [r"Transform GetLeftToeTF\(\)"],
    "GetRightToeTF": [r"Transform GetRightToeTF\(\)"],
    "getLeftHandTF": [r"Transform get_LeftHandTF\(\)"],
    "getRightHandTF": [r"Transform get_RightHandTF\(\)"],
    "getLeftForeArmTF": [r"Transform get_LeftForeArmTF\(\)"],
    "getRightForeArmTF": [r"Transform get_RightForeArmTF\(\)"],

    # Core Functions
    "Curent_Match": [r"CurrentMatch\(\)"],
    "GetLocalPlayer": [r"Player GetLocalPlayer\(\)"],
    "get_IsDieing": [r"Boolean get_IsDieing\(\)"],
    "get_MaxHP": [r"Int32 get_MaxHP\(\)"],
    "get_IsSighting": [r"Boolean get_IsSighting\(\)"],
    "name": [r"String get_NickName\(\)", r"String get_m_NickName\(\)"],
    "Player_GetHeadCollider": [r"Collider get_HeadCollider\(\)"]
}

def parse_dump(dump_path):
    print(f"[*] Dang phan tich file dump: {dump_path}")
    if not os.path.exists(dump_path):
        print(f"[!] Khong tim thay file: {dump_path}")
        return {}

    results = {}
    trailing_hex = re.compile(r"//\s*(0x[0-9a-fA-F]+)\s*$")
    
    line_count = 0
    with open(dump_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line_count += 1
            if line_count % 500000 == 0:
                print(f"    -> Da quet {line_count:,} dong...")

            m_hex = trailing_hex.search(line)
            if not m_hex:
                continue

            rva = m_hex.group(1)

            for target_key, patterns in TARGET_METHODS.items():
                if target_key not in results:
                    for pat in patterns:
                        if re.search(pat, line):
                            results[target_key] = rva
                            print(f"[+] Tim thay [{target_key:22}] -> {rva} | {line.strip()[:80]}")
                            break

    print(f"\n[*] Hoan tat quet {line_count:,} dong. Tim duoc {len(results)}/{len(TARGET_METHODS)} offset.")
    return results

def output_cpp(results, out_path="extracted_offsets.h"):
    lines = [
        "// ===================================================================",
        "// Auto-generated Offsets for Hooks.h",
        "// Generated by Zhee Dev Offset Extractor (com.dts.freefireth)",
        "// ===================================================================\n",
        "void game_sdk_t::init()",
        "{"
    ]

    mapping = [
        ("Curent_Match", "this->Curent_Match = (void *(*)())getRealOffset(oxo(\"{rva}\"));"),
        ("GetLocalPlayer", "this->GetLocalPlayer = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("GetHeadPositions", "this->GetHeadPositions = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("get_IsDieing", "this->get_IsDieing = (bool (*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("get_MaxHP", "this->get_MaxHP = (int (*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("get_IsSighting", "this->get_IsSighting = (bool (*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("name", "this->name = (monoString * (*)(void *player))getRealOffset(oxo(\"{rva}\"));"),
        ("GetHeadPositions", "this->_GetHeadPositions = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("newHipMods", "this->_newHipMods = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("GetLeftAnkleTF", "this->_GetLeftAnkleTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("GetRightAnkleTF", "this->_GetRightAnkleTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("GetLeftToeTF", "this->_GetLeftToeTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("GetRightToeTF", "this->_GetRightToeTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("getLeftHandTF", "this->_getLeftHandTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("getRightHandTF", "this->_getRightHandTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("getLeftForeArmTF", "this->_getLeftForeArmTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));"),
        ("getRightForeArmTF", "this->_getRightForeArmTF = (void *(*)(void *))getRealOffset(oxo(\"{rva}\"));")
    ]

    for key, template in mapping:
        rva = results.get(key, "0x0000000 /* NOT_FOUND */")
        lines.append(f"    {template.format(rva=rva)}")

    lines.append("}\n")
    content = "\n".join(lines)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"\n[+] Da xuat file ma C++ cho Hooks.h tai: {out_path}")
    print("\n" + content)

if __name__ == "__main__":
    dump_file = sys.argv[1] if len(sys.argv) > 1 else "dump.cs"
    res = parse_dump(dump_file)
    if res:
        output_cpp(res)
